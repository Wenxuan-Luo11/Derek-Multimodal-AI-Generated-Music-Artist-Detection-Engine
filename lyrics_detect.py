def predict_lyrics_source(embeddings, model, label_encoder):
    """
    Predicts whether lyrics are AI-generated or human-written and their probability.

    Args:
        embeddings (np.ndarray): The Nomic embeddings of the lyrics (2D array, e.g., (1, 768)).
        model (LogisticRegression): The trained Logistic Regression model.
        label_encoder (LabelEncoder): The label encoder used to transform labels.

    Returns:
        tuple: A tuple containing the predicted label ('AI' or 'Human') and the prediction probability.
    """
    # Get prediction probabilities for both classes
    probabilities = model.predict_proba(embeddings)[0]

    # Get the predicted class index
    predicted_class_idx = model.predict(embeddings)[0]

    # Map the predicted class index back to its original label ('AI' or 'Human')
    predicted_label = label_encoder.inverse_transform([predicted_class_idx])[0]

    # Get the probability for the predicted label
    predicted_probability = probabilities[predicted_class_idx]

    return predicted_label, predicted_probability

