import requests

def fetch_lyrics_from_lrclib(artist_name: str, track_name: str) -> str:
    """
    Fetches lyrics for a given artist and track name from the LRCLIB API.

    Args:
        artist_name (str): The name of the artist.
        track_name (str): The name of the track.

    Returns:
        str: The fetched lyrics, or an error message if not found or an error occurs.
    """
    base_url = "https://lrclib.net/api/search"
    params = {
        "q": f"{artist_name} {track_name}",
        "artist_name": artist_name,
        "track_name": track_name
    }

    try:
        # Make a GET request to the LRCLIB API
        response = requests.get(base_url, params=params, timeout=10)
        response.raise_for_status()  # Raise an HTTPError for bad responses (4xx or 5xx)

        # Parse the JSON response
        data = response.json()

        # Check if any lyrics results are found
        if data and len(data) > 0:
            first_result = data[0]
            lyrics = first_result.get("plainLyrics")
            if lyrics:
                return lyrics
            else:
                return f"No actual lyrics found for '{track_name}' by {artist_name} on LRCLIB. (e.g., instrumental or not in database)."
        else:
            return f"No results found for '{track_name}' by {artist_name} on LRCLIB."

    except requests.exceptions.HTTPError as http_err:
        return f"HTTP error occurred: {http_err} for '{track_name}' by {artist_name}"
    except requests.exceptions.ConnectionError as conn_err:
        return f"Connection error occurred: {conn_err} for '{track_name}' by {artist_name}"
    except requests.exceptions.Timeout as timeout_err:
        return f"Timeout error occurred: {timeout_err} for '{track_name}' by {artist_name}"
    except requests.exceptions.RequestException as req_err:
        return f"An unexpected request error occurred: {req_err} for '{track_name}' by {artist_name}"
    except Exception as e:
        return f"An unexpected error occurred: {e} for '{track_name}' by {artist_name}"

